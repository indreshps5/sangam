"""
DemandObservation — historical demand data point.
Forecast — predicted future demand with confidence intervals.
"""

from datetime import date, datetime
from uuid import UUID

from sqlalchemy import String, Float, Integer, DateTime, Date, ForeignKey, CheckConstraint, Text
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from sangam_api.core.database import Base
from sangam_api.core.types import UUIDPrimaryKeyMixin, TimestampMixin


class DemandObservation(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Historical demand data point for a product at a depot.

    Canonical fields:
    - depot_id: FK to the depot
    - product_category: Category of product demanded
    - sku: Optional specific SKU
    - observation_date: Date of the observation
    - demand_quantity: Observed demand quantity
    - unit_of_measure: Unit for the quantity
    - source: Data source (pos, manual, sensor, etc.)
    - is_outlier: Flag for anomalous observations
    - notes: Additional context
    """

    __tablename__ = "demand_observations"

    __table_args__ = (
        CheckConstraint("demand_quantity >= 0", name="ck_demand_quantity_non_negative"),
    )

    depot_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("depots.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    product_category: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    sku: Mapped[str | None] = mapped_column(String(100), nullable=True, index=True)
    observation_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)
    demand_quantity: Mapped[float] = mapped_column(Float, nullable=False)
    unit_of_measure: Mapped[str] = mapped_column(String(20), nullable=False, default="unit")
    source: Mapped[str] = mapped_column(String(50), nullable=False, default="manual", index=True)
    is_outlier: Mapped[bool] = mapped_column(default=False, index=True)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)


class Forecast(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Demand forecast generated by ML models.

    Canonical fields:
    - depot_id: FK to the target depot
    - product_category: Category being forecasted
    - model_type: Type of ML model used
    - model_version: Version of the model
    - forecast_horizon_days: Number of days into the future
    - confidence_level: Statistical confidence (0.5-0.99)
    - accuracy_score: Backtested accuracy metric (MAPE, etc.)
    - training_data_end_date: Last date of training data
    - parameters: JSON string of model hyperparameters
    - status: Forecast status
    """

    __tablename__ = "forecasts"

    __table_args__ = (
        CheckConstraint("forecast_horizon_days > 0", name="ck_forecasts_horizon_positive"),
        CheckConstraint(
            "confidence_level >= 0.5 AND confidence_level <= 0.99",
            name="ck_forecasts_confidence_range",
        ),
        CheckConstraint("accuracy_score >= 0", name="ck_forecasts_accuracy_non_negative"),
    )

    depot_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("depots.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    product_category: Mapped[str | None] = mapped_column(String(100), nullable=True, index=True)
    model_type: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    model_version: Mapped[str] = mapped_column(String(50), nullable=False)
    forecast_horizon_days: Mapped[int] = mapped_column(Integer, nullable=False)
    confidence_level: Mapped[float] = mapped_column(Float, nullable=False, default=0.95)
    accuracy_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    training_data_end_date: Mapped[date | None] = mapped_column(Date, nullable=True)
    parameters: Mapped[str | None] = mapped_column(Text, nullable=True, comment="JSON model hyperparameters")
    status: Mapped[str] = mapped_column(String(30), nullable=False, default="active", index=True)

    # Relationships
    data_points: Mapped[list["ForecastDataPoint"]] = relationship(
        back_populates="forecast", cascade="all, delete-orphan", lazy="selectin"
    )


class ForecastDataPoint(Base, UUIDPrimaryKeyMixin):
    """
    Individual data point within a forecast.

    Canonical fields:
    - forecast_id: FK to parent forecast
    - forecast_date: Date being predicted
    - predicted_demand: Point estimate
    - lower_bound: Lower confidence bound
    - upper_bound: Upper confidence bound
    """

    __tablename__ = "forecast_data_points"

    __table_args__ = (
        CheckConstraint("predicted_demand >= 0", name="ck_fdp_predicted_non_negative"),
        CheckConstraint("lower_bound <= upper_bound", name="ck_fdp_bounds_order"),
    )

    forecast_id: Mapped[UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("forecasts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    forecast_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)
    predicted_demand: Mapped[float] = mapped_column(Float, nullable=False)
    lower_bound: Mapped[float] = mapped_column(Float, nullable=False)
    upper_bound: Mapped[float] = mapped_column(Float, nullable=False)

    # Relationships
    forecast: Mapped["Forecast"] = relationship(back_populates="data_points", lazy="joined")
