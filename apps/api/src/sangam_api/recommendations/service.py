"""
Recommendation Service

Orchestrates recommendation generation, approval workflows, and execution.
"""

from typing import List, Optional, Dict, Any
from uuid import UUID
from datetime import datetime, timedelta
import logging

from sqlalchemy.ext.asyncio import AsyncSession

from sangam_api.recommendations.models import Recommendation, RecommendationAuditLog
from sangam_api.recommendations.schemas import (
    RecommendationCreate,
    RecommendationUpdate,
    RecommendationStatus,
)
from sangam_api.recommendations.repository import (
    RecommendationRepositoryInterface,
    RecommendationAuditLogRepositoryInterface,
)
from sangam_api.recommendations.strategies import (
    RecommendationStrategy,
    StockTransferStrategy,
    ReplenishmentStrategy,
    RouteOptimizationStrategy,
    ShipmentPriorityStrategy,
    ShortageReviewStrategy,
)
from sangam_api.core.exceptions import NotFoundException, ValidationException, AuthorizationException

logger = logging.getLogger(__name__)


class RecommendationService:
    """
    Service for managing recommendations.
    
    Coordinates recommendation generation using various strategies,
    manages approval workflows, and handles execution.
    """
    
    def __init__(
        self,
        recommendation_repo: RecommendationRepositoryInterface,
        audit_log_repo: RecommendationAuditLogRepositoryInterface,
        db: AsyncSession,
        inventory_service=None,
        forecast_service=None,
        shipment_service=None,
        route_service=None,
    ):
        self.recommendation_repo = recommendation_repo
        self.audit_log_repo = audit_log_repo
        self.db = db
        
        # Initialize strategies
        self.strategies: Dict[str, RecommendationStrategy] = {}
        
        if inventory_service and forecast_service:
            self.strategies['stock_transfer'] = StockTransferStrategy(
                inventory_service, forecast_service
            )
            self.strategies['replenishment'] = ReplenishmentStrategy(
                inventory_service, forecast_service
            )
        
        if shipment_service and route_service:
            self.strategies['route_change'] = RouteOptimizationStrategy(
                shipment_service, route_service
            )
            self.strategies['shipment_priority'] = ShipmentPriorityStrategy(
                shipment_service
            )
        
        if forecast_service and inventory_service:
            self.strategies['shortage_review'] = ShortageReviewStrategy(
                forecast_service, inventory_service
            )
    
    async def generate_recommendations(
        self,
        strategy_names: Optional[List[str]] = None,
        context: Optional[Dict[str, Any]] = None
    ) -> List[Recommendation]:
        """
        Generate recommendations using specified strategies.
        
        Args:
            strategy_names: List of strategy names to use. If None, use all.
            context: Optional context for strategy execution.
        
        Returns:
            List of generated recommendations
        """
        all_recommendations = []
        
        # Determine which strategies to run
        strategies_to_run = strategy_names or list(self.strategies.keys())
        
        for strategy_name in strategies_to_run:
            if strategy_name not in self.strategies:
                logger.warning(f"Strategy '{strategy_name}' not found, skipping")
                continue
            
            strategy = self.strategies[strategy_name]
            
            try:
                logger.info(f"Running strategy: {strategy.get_strategy_name()}")
                recommendations = await strategy.generate_recommendations(context)
                
                # Save each recommendation
                for rec in recommendations:
                    saved_rec = await self.recommendation_repo.create(rec)
                    
                    # Log creation
                    await self._log_action(
                        recommendation_id=saved_rec.id,
                        action='created',
                        new_status='pending',
                        notes=f"Generated by {strategy.get_strategy_name()}"
                    )
                    
                    all_recommendations.append(saved_rec)
                
                logger.info(f"Strategy {strategy_name} generated {len(recommendations)} recommendations")
                
            except Exception as e:
                logger.error(f"Error running strategy {strategy_name}: {str(e)}", exc_info=True)
                continue
        
        await self.db.commit()
        
        return all_recommendations
    
    async def get_recommendation(self, recommendation_id: UUID) -> Recommendation:
        """Get recommendation by ID."""
        recommendation = await self.recommendation_repo.get_by_id(recommendation_id)
        if not recommendation:
            raise NotFoundException("Recommendation", str(recommendation_id))
        return recommendation
    
    async def list_recommendations(
        self,
        skip: int = 0,
        limit: int = 50,
        status: Optional[str] = None,
        recommendation_type: Optional[str] = None,
        category: Optional[str] = None,
        priority: Optional[int] = None,
        affected_depot_id: Optional[UUID] = None,
        affected_shipment_id: Optional[UUID] = None,
        affected_inventory_item_id: Optional[UUID] = None,
        affected_route_id: Optional[UUID] = None,
    ) -> tuple[List[Recommendation], int]:
        """List recommendations with filtering."""
        recommendations = await self.recommendation_repo.list_recommendations(
            skip=skip,
            limit=limit,
            status=status,
            recommendation_type=recommendation_type,
            category=category,
            priority=priority,
            affected_depot_id=affected_depot_id,
            affected_shipment_id=affected_shipment_id,
            affected_inventory_item_id=affected_inventory_item_id,
            affected_route_id=affected_route_id,
        )
        
        total = await self.recommendation_repo.count_recommendations(
            status=status,
            recommendation_type=recommendation_type,
            category=category,
            priority=priority,
            affected_depot_id=affected_depot_id,
            affected_shipment_id=affected_shipment_id,
            affected_inventory_item_id=affected_inventory_item_id,
            affected_route_id=affected_route_id,
        )
        
        return recommendations, total
    
