    async def approve_recommendation(
        self,
        recommendation_id: UUID,
        user_id: UUID,
        user_name: str,
        notes: Optional[str] = None
    ) -> Recommendation:
        """
        Approve a recommendation.
        
        Approval does NOT automatically execute the recommendation.
        Execution requires a separate explicit action.
        """
        recommendation = await self.get_recommendation(recommendation_id)
        
        # Validate state transition
        if recommendation.status != 'pending':
            raise ValidationException(
                f"Cannot approve recommendation in '{recommendation.status}' status. "
                f"Only pending recommendations can be approved."
            )
        
        # Check expiration
        if recommendation.expires_at and recommendation.expires_at < datetime.utcnow():
            raise ValidationException("Cannot approve expired recommendation")
        
        # Update status
        previous_status = recommendation.status
        recommendation.status = 'approved'
        recommendation.approved_by = user_id
        recommendation.approved_at = datetime.utcnow()
        
        recommendation = await self.recommendation_repo.update(recommendation)
        
        # Log approval
        await self._log_action(
            recommendation_id=recommendation.id,
            action='approved',
            previous_status=previous_status,
            new_status='approved',
            user_id=user_id,
            user_name=user_name,
            notes=notes
        )
        
        await self.db.commit()
        
        logger.info(f"Recommendation {recommendation_id} approved by user {user_id}")
        
        return recommendation
    
    async def reject_recommendation(
        self,
        recommendation_id: UUID,
        user_id: UUID,
        user_name: str,
        reason: str
    ) -> Recommendation:
        """Reject a recommendation."""
        recommendation = await self.get_recommendation(recommendation_id)
        
        # Validate state transition
        if recommendation.status != 'pending':
            raise ValidationException(
                f"Cannot reject recommendation in '{recommendation.status}' status. "
                f"Only pending recommendations can be rejected."
            )
        
        # Update status
        previous_status = recommendation.status
        recommendation.status = 'rejected'
        recommendation.rejection_reason = reason
        recommendation.approved_by = user_id  # Track who rejected
        recommendation.approved_at = datetime.utcnow()
        
        recommendation = await self.recommendation_repo.update(recommendation)
        
        # Log rejection
        await self._log_action(
            recommendation_id=recommendation.id,
            action='rejected',
            previous_status=previous_status,
            new_status='rejected',
            user_id=user_id,
            user_name=user_name,
            notes=reason
        )
        
        await self.db.commit()
        
        logger.info(f"Recommendation {recommendation_id} rejected by user {user_id}")
        
        return recommendation
    
    async def execute_recommendation(
        self,
        recommendation_id: UUID,
        user_id: UUID,
        user_name: str,
        notes: Optional[str] = None,
        parameters: Optional[Dict[str, Any]] = None
    ) -> Recommendation:
        """
        Execute an approved recommendation.
        
        This is a simulated execution for the prototype.
        In production, this would integrate with actual operational systems.
        """
        recommendation = await self.get_recommendation(recommendation_id)
        
        # Validate state
        if recommendation.status != 'approved':
            raise ValidationException(
                f"Cannot execute recommendation in '{recommendation.status}' status. "
                f"Only approved recommendations can be executed."
            )
        
        # Simulate execution based on recommendation type
        execution_result = await self._simulate_execution(recommendation, parameters)
        
        # Update status
        previous_status = recommendation.status
        recommendation.status = 'completed'
        recommendation.executed_at = datetime.utcnow()
        recommendation.executed_by = user_id
        recommendation.execution_result = execution_result
        
        recommendation = await self.recommendation_repo.update(recommendation)
        
        # Log execution
        await self._log_action(
            recommendation_id=recommendation.id,
            action='executed',
            previous_status=previous_status,
            new_status='completed',
            user_id=user_id,
            user_name=user_name,
            notes=notes,
            metadata={'execution_result': execution_result}
        )
        
        await self.db.commit()
        
        logger.info(f"Recommendation {recommendation_id} executed by user {user_id}")
        
        return recommendation
    
    async def _simulate_execution(
        self,
        recommendation: Recommendation,
        parameters: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Simulate execution of a recommendation.
        
        In production, this would call actual operational systems.
        For the prototype, we simulate the execution.
        """
        result = {
            'simulated': True,
            'executed_at': datetime.utcnow().isoformat(),
            'recommendation_type': recommendation.recommendation_type,
        }
        
        # Simulate different execution types
        if recommendation.recommendation_type == 'stock_transfer':
            result.update({
                'action': 'stock_transfer_simulated',
                'message': 'Stock transfer would be initiated between depots',
                'estimated_completion': (datetime.utcnow() + timedelta(days=2)).isoformat(),
                'parameters': parameters or {}
            })
        
        elif recommendation.recommendation_type == 'replenishment':
            result.update({
                'action': 'purchase_order_simulated',
                'message': 'Purchase order would be placed with supplier',
                'estimated_delivery': (datetime.utcnow() + timedelta(days=7)).isoformat(),
                'parameters': parameters or {}
            })
        
        elif recommendation.recommendation_type == 'route_change':
            result.update({
                'action': 'route_reassignment_simulated',
                'message': 'Shipment would be reassigned to alternative route',
                'estimated_time_savings': '4-6 hours',
                'parameters': parameters or {}
            })
        
        elif recommendation.recommendation_type == 'shipment_priority':
            result.update({
                'action': 'shipment_expediting_simulated',
                'message': 'Carrier would be contacted to expedite shipment',
                'estimated_delay_reduction': '50%',
                'parameters': parameters or {}
            })
        
        elif recommendation.recommendation_type == 'shortage_review':
            result.update({
                'action': 'review_initiated',
                'message': 'Shortage review process initiated',
                'next_steps': [
                    'Review demand forecast accuracy',
                    'Contact suppliers for emergency procurement',
                    'Alert sales team about potential stockout'
                ],
                'parameters': parameters or {}
            })
        
        else:
            result.update({
                'action': 'generic_execution_simulated',
                'message': 'Recommendation execution simulated',
                'parameters': parameters or {}
            })
        
        return result
    
