"""
Recommendation Database Models

Defines the data structures for recommendations and approval workflows.
"""

from datetime import datetime
from sqlalchemy import Column, String, Float, Integer, DateTime, ForeignKey, Text, JSON
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
import uuid

from sangam_api.core.database import Base


class Recommendation(Base):
    """
    Represents a logistics recommendation generated by the system.
    
    Recommendations are suggestions for actions that can improve
    supply chain operations. They require approval before execution.
    """
    
    __tablename__ = "recommendations"
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    
    # Recommendation type and category
    recommendation_type = Column(String(50), nullable=False, index=True)  # stock_transfer, replenishment, route_change, etc.
    category = Column(String(50), nullable=False, index=True)  # inventory, shipment, route, forecast
    priority = Column(Integer, nullable=False, default=3)  # 1=critical, 5=low
    
    # Status and workflow
    status = Column(String(20), nullable=False, default='pending', index=True)  # pending, approved, rejected, completed
    
    # Affected entities
    affected_depot_id = Column(UUID(as_uuid=True), ForeignKey('depots.id'), nullable=True, index=True)
    affected_shipment_id = Column(UUID(as_uuid=True), ForeignKey('shipments.id'), nullable=True, index=True)
    affected_inventory_item_id = Column(UUID(as_uuid=True), ForeignKey('inventory_items.id'), nullable=True, index=True)
    affected_route_id = Column(UUID(as_uuid=True), ForeignKey('routes.id'), nullable=True, index=True)
    
    # Recommendation content
    title = Column(String(200), nullable=False)
    description = Column(Text, nullable=False)
    rationale = Column(Text, nullable=False)
    suggested_action = Column(Text, nullable=False)
    
    # Supporting data
    supporting_data = Column(JSON, nullable=True)  # Additional context and data
    assumptions = Column(JSON, nullable=True)  # Assumptions made
    
    # Impact estimation
    estimated_impact = Column(JSON, nullable=True)  # Estimated benefits/costs
    confidence_score = Column(Float, nullable=False, default=0.0)  # 0.0 to 1.0
    
    # Source information
    source_service = Column(String(50), nullable=False)  # Which service generated this
    source_records = Column(JSON, nullable=True)  # IDs of source records
    
    # Timestamps
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    updated_at = Column(DateTime, nullable=False, default=datetime.utcnow, onupdate=datetime.utcnow)
    expires_at = Column(DateTime, nullable=True)  # When this recommendation expires
    
    # Approval workflow
    created_by = Column(UUID(as_uuid=True), ForeignKey('users.id'), nullable=True)
    approved_by = Column(UUID(as_uuid=True), ForeignKey('users.id'), nullable=True)
    approved_at = Column(DateTime, nullable=True)
    rejection_reason = Column(Text, nullable=True)
    
    # Execution tracking
    executed_at = Column(DateTime, nullable=True)
    executed_by = Column(UUID(as_uuid=True), ForeignKey('users.id'), nullable=True)
    execution_result = Column(JSON, nullable=True)  # Result of execution
    
    # Relationships
    depot = relationship("Depot", foreign_keys=[affected_depot_id])
    shipment = relationship("Shipment", foreign_keys=[affected_shipment_id])
    inventory_item = relationship("InventoryItem", foreign_keys=[affected_inventory_item_id])
    route = relationship("Route", foreign_keys=[affected_route_id])
    creator = relationship("User", foreign_keys=[created_by])
    approver = relationship("User", foreign_keys=[approved_by])
    executor = relationship("User", foreign_keys=[executed_by])
    
    def __repr__(self):
        return f"<Recommendation(id={self.id}, type={self.recommendation_type}, status={self.status})>"


class RecommendationAuditLog(Base):
    """
    Audit log for recommendation actions.
    
    Tracks all state changes and actions taken on recommendations.
    """
    
    __tablename__ = "recommendation_audit_logs"
    
    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    recommendation_id = Column(UUID(as_uuid=True), ForeignKey('recommendations.id'), nullable=False, index=True)
    
    # Action details
    action = Column(String(50), nullable=False)  # created, approved, rejected, executed
    previous_status = Column(String(20), nullable=True)
    new_status = Column(String(20), nullable=True)
    
    # User information
    user_id = Column(UUID(as_uuid=True), ForeignKey('users.id'), nullable=True)
    user_name = Column(String(100), nullable=True)
    
    # Additional context
    notes = Column(Text, nullable=True)
    metadata = Column(JSON, nullable=True)
    
    # Timestamp
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    
    # Relationships
    recommendation = relationship("Recommendation")
    user = relationship("User")
    
    def __repr__(self):
        return f"<RecommendationAuditLog(id={self.id}, action={self.action})>"
